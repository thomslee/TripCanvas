def search_cities(keyword: str = "", limit: int = 50) -> list[dict]:
    """搜索城市，支持中文和拼音。"""
    if not keyword:
        return [{"name": c[0], "pinyin": c[1], "province": c[2]} for c in CITIES[:limit]]
    kw = keyword.lower().strip()
    results = []
    for name, pinyin, province in CITIES:
        if kw in name or kw in pinyin or kw in province.lower():
            results.append({"name": name, "pinyin": pinyin, "province": province})
            if len(results) >= limit:
                break
    return results
